import { MappingConnection, CanSignal, VhalProperty } from '../types/automotive';

export interface CodeGenOptions {
  serviceClassName?: string;
  namespace?: string;
  includeSafetyGuards?: boolean;
  generateComments?: boolean;
}

export function synthesizeVhalCpp(
  connections: MappingConnection[],
  options: CodeGenOptions = {}
): string {
  const {
    serviceClassName = 'CanVhalHalService',
    namespace = 'aidl::android::hardware::automotive::vehicle::impl',
    includeSafetyGuards = true,
    generateComments = true,
  } = options;

  if (connections.length === 0) {
    return `// ============================================================================
// CAN-to-AOSP VHAL Auto-Generated Translation Unit
// Status: No active CAN-to-VHAL mappings configured.
// ============================================================================
// Add signals to the canvas and create connections to generate production C++ code.
`;
  }

  // Group connections by CAN Message ID
  const messageGroups = new Map<number, { hexId: string; msgName: string; conns: MappingConnection[] }>();

  for (const conn of connections) {
    const msgId = conn.canMessageId;
    if (!messageGroups.has(msgId)) {
      messageGroups.set(msgId, {
        hexId: `0x${msgId.toString(16).toUpperCase()}`,
        msgName: conn.signal.messageName || `MSG_0x${msgId.toString(16).toUpperCase()}`,
        conns: [],
      });
    }
    messageGroups.get(msgId)!.conns.push(conn);
  }

  const caseBlocks: string[] = [];

  for (const [msgId, group] of messageGroups.entries()) {
    const signalBlocks: string[] = [];

    for (const conn of group.conns) {
      const sig = conn.signal;
      const prop = conn.property;
      const tf = conn.transform;
      const varPrefix = sanitizeIdentifier(sig.name);

      const unpackCode = generateSignalUnpack(sig, varPrefix);
      const mathCode = generateMathTransform(sig, prop, tf, varPrefix);
      const propDispatchCode = generatePropDispatch(prop, varPrefix);

      signalBlocks.push(`            // Signal: ${sig.name} -> VehicleProperty::${prop.name}
${unpackCode}
${mathCode}
${propDispatchCode}`);
    }

    const caseBody = signalBlocks.join('\n\n');
    caseBlocks.push(`        // --------------------------------------------------------------------
        // CAN Frame: ${group.msgName} (${group.hexId})
        // --------------------------------------------------------------------
        case ${group.hexId}: {
${includeSafetyGuards ? `            if (frame.can_dlc < 8) {\n                // Frame DLC safety verification\n                break;\n            }\n\n` : ''}${caseBody}
            break;
        }`);
  }

  const fullSource = `// ============================================================================
// AUTO-GENERATED BY CAN-TO-AOSP VHAL STUDIO
// Architecture: Android Automotive OS (AAOS / AOSP) AIDL IVehicle
// Compliance: MISRA-C++ / Google C++ Style Guide
// Generated at: ${new Date().toISOString()}
// Total Mappings: ${connections.length} across ${messageGroups.size} CAN Messages
// ============================================================================

#include <aidl/android/hardware/automotive/vehicle/VehicleProperty.h>
#include <aidl/android/hardware/automotive/vehicle/VehiclePropValue.h>
#include <aidl/android/hardware/automotive/vehicle/RawPropModel.h>
#include <linux/can.h>
#include <utils/SystemClock.h>
#include <cstdint>
#include <vector>

namespace ${namespace} {

using aidl::android::hardware::automotive::vehicle::VehicleProperty;
using aidl::android::hardware::automotive::vehicle::VehiclePropValue;
using aidl::android::hardware::automotive::vehicle::RawPropModel;
using android::elapsedRealtimeNano;

/**
 * @brief Processes incoming raw Linux SocketCAN frames and translates
 *        them into standard AOSP AIDL VehiclePropValue events.
 * @param frame Const reference to raw Linux can_frame.
 */
void ${serviceClassName}::onCanFrameReceived(const struct can_frame& frame) {
    const int64_t timestamp = elapsedRealtimeNano();

    switch (frame.can_id & CAN_EFF_MASK) {
${caseBlocks.join('\n\n')}

        default:
            // Non-mapped CAN frame ID received on bus
            break;
    }
}

} // namespace ${namespace}
`;

  return fullSource;
}

function sanitizeIdentifier(name: string): string {
  return name.replace(/[^a-zA-Z0-9_]/g, '_').toLowerCase();
}

function generateSignalUnpack(sig: CanSignal, varPrefix: string): string {
  const isLittle = sig.endianness === 'little';
  const startByte = Math.floor(sig.startBit / 8);
  const bitOffsetInByte = sig.startBit % 8;

  // Single bit boolean flag
  if (sig.length === 1) {
    return `            const bool raw_${varPrefix} = ((frame.data[${startByte}] >> ${bitOffsetInByte}) & 0x01U) != 0U;`;
  }

  // Byte-aligned 8-bit signal
  if (sig.length === 8 && bitOffsetInByte === 0) {
    if (sig.isSigned) {
      return `            const int8_t raw_${varPrefix} = static_cast<int8_t>(frame.data[${startByte}]);`;
    }
    return `            const uint8_t raw_${varPrefix} = frame.data[${startByte}];`;
  }

  // 16-bit signal
  if (sig.length === 16 && bitOffsetInByte === 0) {
    if (isLittle) {
      // Intel
      const expr = `(static_cast<uint16_t>(frame.data[${startByte}])) | (static_cast<uint16_t>(frame.data[${startByte + 1}]) << 8U)`;
      if (sig.isSigned) {
        return `            const int16_t raw_${varPrefix} = static_cast<int16_t>(${expr});`;
      }
      return `            const uint16_t raw_${varPrefix} = ${expr};`;
    } else {
      // Motorola
      const expr = `(static_cast<uint16_t>(frame.data[${startByte}]) << 8U) | (static_cast<uint16_t>(frame.data[${startByte + 1}]))`;
      if (sig.isSigned) {
        return `            const int16_t raw_${varPrefix} = static_cast<int16_t>(${expr});`;
      }
      return `            const uint16_t raw_${varPrefix} = ${expr};`;
    }
  }

  // Generic bit-field extraction
  const numBytes = Math.ceil((bitOffsetInByte + sig.length) / 8);
  const maskHex = `0x${((1n << BigInt(sig.length)) - 1n).toString(16).toUpperCase()}ULL`;

  if (isLittle) {
    // Combine little endian bytes
    const byteShifts = [];
    for (let b = 0; b < numBytes && startByte + b < 8; b++) {
      byteShifts.push(`(static_cast<uint64_t>(frame.data[${startByte + b}]) << ${b * 8}ULL)`);
    }
    const combined = byteShifts.join(' | ');
    let res = `            const uint64_t raw_bits_${varPrefix} = (${combined});\n`;
    res += `            const uint64_t raw_${varPrefix} = (raw_bits_${varPrefix} >> ${bitOffsetInByte}ULL) & ${maskHex};`;
    return res;
  } else {
    // Combine big endian bytes
    const byteShifts = [];
    for (let b = 0; b < numBytes && startByte + b < 8; b++) {
      const shift = (numBytes - 1 - b) * 8;
      byteShifts.push(`(static_cast<uint64_t>(frame.data[${startByte + b}]) << ${shift}ULL)`);
    }
    const combined = byteShifts.join(' | ');
    let res = `            const uint64_t raw_bits_${varPrefix} = (${combined});\n`;
    res += `            const uint64_t raw_${varPrefix} = (raw_bits_${varPrefix} >> ${bitOffsetInByte}ULL) & ${maskHex};`;
    return res;
  }
}

function generateMathTransform(
  sig: CanSignal,
  prop: VhalProperty,
  tf: MappingConnection['transform'],
  varPrefix: string
): string {
  // If signal is 1 bit boolean
  if (sig.length === 1 && prop.dataType === 'booleanValues') {
    return `            const bool val_${varPrefix} = raw_${varPrefix};`;
  }

  // If custom expression specified
  if (tf.customExpression && tf.customExpression.trim() && tf.customExpression.includes('raw')) {
    const sanitizedExpr = tf.customExpression
      .replace(/\braw\b/g, `static_cast<float>(raw_${varPrefix})`)
      .replace(/f\b/g, 'f');
    return `            // Custom engineering arithmetic\n            const float val_${varPrefix} = ${sanitizedExpr};`;
  }

  // Standard DBC physical scaling: (raw * scale) + offset
  const scale = sig.scale !== undefined ? sig.scale : 1.0;
  const offset = sig.offset !== undefined ? sig.offset : 0.0;
  const multiplier = tf.scaleMultiplier !== undefined ? tf.scaleMultiplier : 1.0;
  const addition = tf.offsetAddition !== undefined ? tf.offsetAddition : 0.0;

  const totalScale = scale * multiplier;
  const totalOffset = offset + addition;

  if (totalScale === 1.0 && totalOffset === 0.0) {
    if (prop.dataType === 'int32Values' || prop.dataType === 'int64Values') {
      return `            const auto val_${varPrefix} = raw_${varPrefix};`;
    }
    return `            const float val_${varPrefix} = static_cast<float>(raw_${varPrefix});`;
  }

  const scaleStr = Number.isInteger(totalScale) ? `${totalScale}.0f` : `${totalScale}f`;
  const offsetStr = totalOffset > 0
    ? ` + ${Number.isInteger(totalOffset) ? `${totalOffset}.0f` : `${totalOffset}f`}`
    : totalOffset < 0
    ? ` - ${Math.abs(totalOffset)}f`
    : '';

  return `            const float val_${varPrefix} = (static_cast<float>(raw_${varPrefix}) * ${scaleStr})${offsetStr};`;
}

function generatePropDispatch(prop: VhalProperty, varPrefix: string): string {
  let valueVectorInit = '';

  switch (prop.dataType) {
    case 'floatValues':
      valueVectorInit = `prop_${varPrefix}.value.floatValues = { static_cast<float>(val_${varPrefix}) };`;
      break;
    case 'int32Values':
      valueVectorInit = `prop_${varPrefix}.value.int32Values = { static_cast<int32_t>(val_${varPrefix}) };`;
      break;
    case 'booleanValues':
      valueVectorInit = `prop_${varPrefix}.value.booleanValues = { static_cast<bool>(val_${varPrefix}) };`;
      break;
    case 'int64Values':
      valueVectorInit = `prop_${varPrefix}.value.int64Values = { static_cast<int64_t>(val_${varPrefix}) };`;
      break;
    default:
      valueVectorInit = `prop_${varPrefix}.value.floatValues = { static_cast<float>(val_${varPrefix}) };`;
      break;
  }

  return `            VehiclePropValue prop_${varPrefix};
            prop_${varPrefix}.prop = static_cast<int32_t>(VehicleProperty::${prop.name});
            prop_${varPrefix}.areaId = 0;
            prop_${varPrefix}.timestamp = timestamp;
            ${valueVectorInit}
            mCallback->onPropertyEvent({ prop_${varPrefix} });`;
}

